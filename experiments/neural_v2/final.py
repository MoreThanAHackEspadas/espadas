"""Write the shipped models from the networks trained on all ten external matches, and check them.

    python final.py export VARIANT [--blind-mode split|avg|blind|none] [--blind-seeds 0] [--out-dir DIR]
    python final.py check  VARIANT [--blind-mode ...] [--blind-seeds ...] [--game 1] [--level medium]

export: neural_weights.py, blind_weights.py (unless --blind-mode none) and evidence_models.py into
DIR (default: the repo's espadas/), then reads them back and asserts every array is the same.
check: the package path (NumPy, from raw tracking, what the build runs) against the experiment path
(PyTorch on the cached view) on one external match, with the models in memory; exit 1 if the team
log-odds differ by more than 0.01 anywhere or fewer than 99.5% of the labels are equal. The
experiment path is skipped without a GPU. Networks and tree models are loaded from the cache (a
network not cached yet is trained: GPU).
"""
import argparse, importlib.util, os, sys, time
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nexp, blind                                           # noqa: E402
from nexp import neural, v4, bench, fit_neural, config       # noqa: E402
from espadas import blind as pkg_blind, evidence             # noqa: E402
from espadas.external import degrade                         # noqa: E402


def models(a):
    """(team nets, mirror, blind nets, tree models) trained on a.train_games."""
    games, spec = tuple(a.train_games), nexp.VARIANTS[a.variant]
    ws = [nexp.fitted(games, nexp.cfg_of(a.variant, s)) for s in spec.get("seeds", [0])]
    bws = [] if a.blind_mode == "none" else \
        [blind.fitted(games, dict(blind.CFG, seed=s)) for s in a.blind_seeds]
    return ws, spec.get("tta", False), bws, fit_neural.dead_models(games)


def header(a, what, mirror):
    games = " ".join(map(str, sorted(a.train_games)))
    spent = (" (all ten: the five spent held-out games are included, see docs/refinement2_rule.md)"
             if tuple(sorted(a.train_games)) == tuple(nexp.ALL) else "")
    return ('"""Generated by experiments/neural_v2/final.py; do not edit by hand.\n\n'
            "{} fitted on external games {}{}.\nVariant {}, seeds {}, mirror {}, blind mode {}"
            '.\n"""\n\n'.format(what, games, spent, a.variant,
                                nexp.VARIANTS[a.variant].get("seeds", [0]), mirror, a.blind_mode))


def load_module(path):
    spec = importlib.util.spec_from_file_location(os.path.basename(path)[:-3], path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def same(x, y, what):
    assert list(x["names"]) == list(y["names"]), what + ": names"
    assert [int(d) for d in x["dilations"]] == [int(d) for d in y["dilations"]], what + ": dilations"
    assert set(x) == set(y), what + ": keys"
    for k in x:
        if k not in ("names", "dilations"):
            assert np.array_equal(np.asarray(x[k], dtype="<f4"), np.asarray(y[k], dtype="<f4")), \
                "{}: {}".format(what, k)


def cmd_export(a):
    ws, mirror, bws, trees = models(a)
    os.makedirs(a.out_dir, exist_ok=True)
    path = lambda n: os.path.join(a.out_dir, n)
    files = {"neural_weights.py": header(a, "Neural team evidence model", mirror)
             + "PACKED = {!r}\n".format(neural.pack_many(ws, mirror))}
    dead_model = dict(trees, blind=a.blind_mode) if bws else dict(trees)
    if bws:
        files["blind_weights.py"] = (header(a, "Ball-blind dead network", mirror)
                                     + "PACKED = {!r}\n".format({"nets": [pkg_blind.pack(w) for w in bws]}))
    files["evidence_models.py"] = (header(a, "Evidence models: dead = boosted trees (as "
                                         "tools/fit_evidence.py --model boosted)"
                                         + (" and the ball-blind network" if bws else "")
                                         + ", team = the network of espadas/neural.py", mirror)
                                   + "DEAD_MODEL = {!r}\n\nTEAM_MODEL = {{\"design\": \"neural\"}}\n".format(dead_model))
    for name, text in files.items():
        with open(path(name), "w") as f:
            f.write(text)
    # round trip: read the files back and compare with what is in memory
    packed = load_module(path("neural_weights.py")).PACKED
    assert bool(packed["mirror"]) == bool(mirror) and len(packed["nets"]) == len(ws)
    for i, (p, w) in enumerate(zip(packed["nets"], ws)):
        same(neural.unpack(p), w, "team net {}".format(i))
    if bws:
        packed = load_module(path("blind_weights.py")).PACKED
        assert len(packed["nets"]) == len(bws)
        for i, (p, w) in enumerate(zip(packed["nets"], bws)):
            want = {k: v for k, v in w.items() if k != "cols"}
            want["names"] = [w["names"][j][len("dead:"):] for j in w["cols"]]
            same(neural.unpack(p), want, "blind net {}".format(i))
    m = load_module(path("evidence_models.py"))
    assert repr(m.DEAD_MODEL) == repr(dead_model) and m.TEAM_MODEL == {"design": "neural"}
    print("round trip ok")
    for name in files:
        print("  {:<20} {:>10,} bytes".format(name, os.path.getsize(path(name))))
    return 0


def cmd_check(a):
    ws, mirror, bws, trees = models(a)
    tag = "std_" + a.level
    (n, game), = bench.available([a.game], heldout=True)
    gt_codes, tracking, graded = bench.setup(game, degrade.LIVE_MISSING, a.level)
    mode = None if not bws else a.blind_mode
    dead_model = dict(trees) if mode is None else dict(
        trees, blind=mode, blind_w=[neural.unpack(pkg_blind.pack(w)) for w in bws])
    team_model = {"design": "neural", "w": ws, "mirror": mirror}

    c = evidence.clues(tracking)                           # package path
    dead, team = evidence.log_odds(c, dead_model, team_model)
    change = c["change_lo"]
    original = evidence._fitted
    evidence._fitted = lambda: (dead_model, team_model)    # as tools/logo.py using_models
    try:
        t0 = time.time()
        f = v4.features(tracking)
        build_s = time.time() - t0
    finally:
        evidence._fitted = original
    labels = v4.decode(f)
    f1 = bench.evaluate(gt_codes, labels, graded)["spell_f1_mean"]
    print("game {} {}: package path spellF1 {:.4f}, v4.features {:.1f} s".format(a.game, a.level, f1, build_s))

    import torch
    if not torch.cuda.is_available():
        print("no GPU: experiment-path comparison skipped")
        return 0
    view = nexp.mm_view(a.game, tag)                       # experiment path
    outs = np.round(np.mean([nexp.apply_gpu(w, view, nexp.cfg_of(a.variant, s), tta=mirror)
                             for w, s in zip(ws, nexp.VARIANTS[a.variant].get("seeds", [0]))], axis=0), 3)
    full = fit_neural.load_view(a.game, tag, features=True)
    e_dead = fit_neural.dead_log_odds(trees, full)
    if mode is not None:
        b = np.mean([blind.apply_gpu(w, view, dict(blind.CFG)) for w in bws], axis=0)
        present = np.asarray(full["features"]["present"], dtype=bool)
        e_dead = {"blind": b, "split": np.where(present, e_dead, b),
                  "avg": np.where(present, 0.5 * (b + e_dead), b)}[mode]
    e_f = dict(full["features"], dead_lo=np.asarray(e_dead, dtype=float), team_lo=outs[:, 1],
               change_lo=outs[:, 2])
    worst = {}
    for name, p, e in (("dead", dead, e_dead), ("team", team, outs[:, 1]), ("change", change, outs[:, 2])):
        d = np.abs(np.asarray(p, dtype=float) - e)
        worst[name] = d.max()
        print("{:<7} max abs diff {:.4f}, frames differing by more than 0.01: {:.2%}".format(
            name, d.max(), np.mean(d > 0.01)))
    e_labels = v4.decode(e_f)
    equal = float(np.mean(labels == e_labels))
    e_f1 = bench.evaluate(gt_codes, e_labels, graded)["spell_f1_mean"]
    print("labels equal {:.4%} | spellF1 package {:.4f} experiment {:.4f}".format(equal, f1, e_f1))
    bad = worst["team"] > 0.01 or equal < 0.995
    print("FAIL" if bad else "ok")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=("export", "check"))
    ap.add_argument("variant")
    ap.add_argument("--blind-mode", default="split", choices=("split", "avg", "blind", "none"))
    ap.add_argument("--blind-seeds", nargs="+", type=int, default=[0])
    ap.add_argument("--out-dir", default=os.path.join(nexp.ROOT, "espadas"))
    ap.add_argument("--game", type=int, default=1)
    ap.add_argument("--level", default="medium")
    ap.add_argument("--train-games", nargs="+", type=int, default=list(nexp.ALL),
                    help=argparse.SUPPRESS)          # smoke tests only
    a = ap.parse_args()
    config.seed_everything()
    sys.exit({"export": cmd_export, "check": cmd_check}[a.command](a))
